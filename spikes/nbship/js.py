"""A `mod_maker` for `nbdev.export.nb_export` that writes an ESM package instead of a Python module.

Nothing here patches fastcore: `javascript` is already in its comment-character map, so `//| export`
in a JavaScript notebook is seen as a directive today. And JavaScript's `export` keyword is the
export list, so like Rust and unlike Python there is no `__all__` to reconstruct and no parser to
write -- the maker concatenates and writes a manifest.

Two artefacts come out of one source, and two tools make them. A CDN wants one minified file at a
versioned URL, which is `deno bundle` (esbuild underneath, so tree-shaken). npm wants unbundled ESM
with a declaration file, and the declarations come from `tsc --allowJs`, which reads the JSDoc the
cells were written with. `deno bundle --declaration` is not the tool for the second: on a
JavaScript entry it emits a re-export carrying an absolute `file://` path, which is worse than
having no declarations at all.
"""
from __future__ import annotations
import json, shutil, subprocess
from pathlib import Path

__all__ = ['EsmMaker', 'esm_maker', 'bundle', 'declarations', 'ToolMissing']

class ToolMissing(RuntimeError):
    "Raised instead of guessing when a build tool is not installed."

class EsmMaker:
    """Write one exported notebook into `src/<name>.js`, and keep `mod.js` re-exporting them all.

    `nb_export` builds one of these per module and calls `make`, so a package is assembled across
    however many notebooks it has: each writes its own file and rejoins the index.
    """
    pkg = 'nbpkg'
    version = '0.1.0'
    description = ''
    def __init__(self, dest, name, nb_path, is_new=True, parse=True, solo_nb=False):
        self.dest, self.name, self.nb_path = Path(dest), name, Path(nb_path)
        self.fname = self.dest/'src'/f"{name.replace('.', '/')}.js"
    def make(self, cells, all_cells=None, lib_path=None):
        self.fname.parent.mkdir(parents=True, exist_ok=True)
        src = '\n\n'.join(c.source.strip() for c in cells
                          if c.cell_type == 'code' and c.source.strip())
        self.fname.write_text(
            f'// AUTOGENERATED! DO NOT EDIT! File to edit: {self.nb_path.name}.\n\n{src}\n',
            encoding='utf-8')
        self._pkg()
    def _mods(self):
        return sorted(p.relative_to(self.dest/'src').with_suffix('').as_posix()
                      for p in (self.dest/'src').rglob('*.js'))
    def _pkg(self):
        mods = self._mods()
        (self.dest/'mod.js').write_text(
            '// AUTOGENERATED! DO NOT EDIT! Written by EsmMaker.\n\n'
            + ''.join(f"export * from './src/{m}.js';\n" for m in mods), encoding='utf-8')
        (self.dest/'package.json').write_text(json.dumps({
            'name': self.pkg, 'version': self.version, 'description': self.description,
            'type': 'module', 'main': 'mod.js', 'module': 'mod.js', 'types': 'types/mod.d.ts',
            'exports': {'.': {'types': './types/mod.d.ts', 'default': './mod.js'},
                        **{f'./{m}': f'./src/{m}.js' for m in mods}},
            'files': ['mod.js', 'src', 'types', 'dist'],
            'sideEffects': False,
        }, indent=2) + '\n', encoding='utf-8')

def esm_maker(pkg, version='0.1.0', description=''):
    "An `EsmMaker` bound to one package name, ready to hand to `nb_export(mod_maker=...)`."
    return type('BoundEsmMaker', (EsmMaker,), {'pkg': pkg, 'version': version,
                                               'description': description})

def _tool(name, dest=None, exe=None):
    "A build tool, from the argument, the package's own `node_modules`, or PATH."
    if exe: return exe
    if dest and (local := Path(dest)/'node_modules'/'.bin'/name).is_file(): return str(local)
    if (found := shutil.which(name)): return found
    raise ToolMissing(f'{name} is not installed')

def _run(argv, cwd, what):
    r = subprocess.run(argv, cwd=cwd, capture_output=True, text=True, timeout=900)
    if r.returncode: raise RuntimeError(f'{what} failed:\n{(r.stderr or r.stdout)[-2000:]}')
    return r

def bundle(dest, name=None, minify=True, platform='browser', exe=None):
    "One file a CDN can serve, tree-shaken and minified, from a package `EsmMaker` wrote."
    dest = Path(dest)
    pkg = json.loads((dest/'package.json').read_text())
    out = dest/'dist'/f"{name or pkg['name']}-{pkg['version']}.min.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    argv = [_tool('deno', dest, exe), 'bundle', '--quiet', f'--platform={platform}',
            '--output', str(out)]
    if minify: argv.append('--minify')
    _run([*argv, 'mod.js'], dest, 'deno bundle')
    return out

def declarations(dest, exe=None):
    "The `.d.ts` tree npm reads, generated from the JSDoc the cells were written with."
    dest = Path(dest)
    _run([_tool('tsc', dest, exe), 'mod.js', '--allowJs', '--declaration',
          '--emitDeclarationOnly', '--outDir', 'types'], dest, 'tsc')
    return dest/'types'/'mod.d.ts'
