"The contracts a workspace depends on, and the registry that satisfies them."

from __future__ import annotations
from typing import Any, Protocol, runtime_checkable
import os

__all__ = ['MemoryPort', 'SearchPort', 'RuntimePort', 'register', 'provider', 'build',
           'providers_for', 'selected', 'ProviderError']

@runtime_checkable
class MemoryPort(Protocol):
    "Durable prose memory: pages, research briefs, agent notes and state."
    note: str
    def search(self, query, limit: int = 8) -> Any: ...
    def context(self, query, sections: int = 6, related: int = 6, max_read: int = 6000) -> Any: ...
    def clusters(self, limit: int = 20) -> Any: ...
    def toc(self, doc=None, depth: int = 3) -> Any: ...
    def read(self, node_id, max_chars: int = 40_000) -> Any: ...
    def exact_text(self, doc_id) -> Any: ...
    def remember(self, doc, query: str = '', force: bool = False, extra_meta=None) -> Any: ...
    def remember_research(self, query, docs, digest) -> Any: ...
    def agent_notes(self, limit: int = 200) -> Any: ...
    def agent_states(self, limit: int = 40) -> Any: ...
    def agent_state_text(self, doc_id) -> Any: ...
    def remember_agent_note(self, title, text, previous_id: str = '') -> Any: ...
    def remember_agent_state(self, title, text, meta=None) -> Any: ...
    def documents(self, limit: int = 80) -> Any: ...
    def forget(self, doc_id) -> Any: ...
    def purge(self, ids=None) -> Any: ...
    def status(self) -> Any: ...

@runtime_checkable
class SearchPort(Protocol):
    "Code search: literal, semantic, and the call graph over a project."
    note: str
    backend: str
    def search(self, q, limit: int = 60, regex: bool = False, force_scan: bool = False,
               mode: str = 'rg') -> Any: ...
    def agent_search(self, q, limit: int = 20) -> Any: ...
    def similar(self, path, line: int = 1, limit: int = 15) -> Any: ...
    def peers(self, path, line: int = 1, limit: int = 25, min_count=None, max_count=None) -> Any: ...
    def clusters(self, min_count=None, max_count=None) -> Any: ...
    def definitions(self, name, path=None, limit: int = 30) -> Any: ...
    def usages(self, name, limit: int = 200) -> Any: ...
    def symbols(self, path) -> Any: ...
    def package_api(self, package) -> Any: ...
    def completion_patches(self, code, pos, limit: int = 50) -> Any: ...
    def merge_completions(self, code, pos, runtime=None, limit: int = 50) -> Any: ...
    def sync(self, notebooks: bool = True, graph: bool = True) -> Any: ...
    def async_sync(self, notebooks: bool = True, graph: bool = True) -> Any: ...
    def status(self) -> Any: ...

@runtime_checkable
class RuntimePort(Protocol):
    "One conversational model session: history, streaming, tools, cancellation."
    spec: Any
    ready: bool
    busy: bool
    hist: Any
    def start(self) -> Any: ...
    def close(self) -> Any: ...
    def cancel(self) -> Any: ...
    def retry(self) -> Any: ...
    def send(self, msg, **kw) -> Any: ...
    def stream(self, msg, **kw) -> Any: ...
    def oneshot(self, prompt, sp: str = '', max_tokens=None) -> Any: ...
    def refresh(self, sp, tools) -> Any: ...
    def set_approve(self, approve) -> Any: ...
    def snapshot_hist(self) -> Any: ...
    def restore_hist(self, hist) -> Any: ...
    def replace_hist(self, summary, keep=()) -> Any: ...
    def count_tokens(self, *a, **kw) -> Any: ...


_REGISTRY: dict[str, dict[str, callable]] = {}

ENV = {'memory': 'LEELA_MEMORY', 'search': 'LEELA_SEARCH', 'runtime': 'LEELA_RUNTIME'}

DEFAULT = 'leela'

class ProviderError(RuntimeError):
    "An implementation was asked for by name and could not be produced."

def register(port, name, factory):
    "Make `name` available for `port`; re-registering the same name replaces it."
    _REGISTRY.setdefault(port, {})[name] = factory
    return factory

def provider(port, name):
    "Decorator form of `register`."
    def deco(fn): return register(port, name, fn)
    return deco

def providers_for(port):
    "Every registered provider name for `port`, defaults first."
    names = sorted(_REGISTRY.get(port, {}))
    return ([DEFAULT] if DEFAULT in names else []) + [n for n in names if n != DEFAULT]

def selected(port, override=None):
    "Which provider `port` should use: explicit override, then environment, then the default."
    if override: return override
    return os.environ.get(ENV.get(port, ''), '') or DEFAULT

def build(port, *a, override=None, **kw):
    "Construct the implementation selected for `port`, raising rather than falling back."
    name = selected(port, override)
    factories = _REGISTRY.get(port, {})
    if name not in factories:
        known = ', '.join(providers_for(port)) or 'none registered'
        raise ProviderError(f'unknown {port} provider {name!r}; available: {known}')
    try:
        return factories[name](*a, **kw)
    except ImportError as e:
        raise ProviderError(
            f'{port} provider {name!r} is selected but its package is not installed: {e}') from e
    except Exception as e:
        raise ProviderError(f'{port} provider {name!r} failed to start: {type(e).__name__}: {e}') from e
