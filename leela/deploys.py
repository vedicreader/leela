"""Getting a web app onto a VM: a Dockerfile, a tunnel, a server, and the keys CI needs.

The shape is [lego](https://github.com/Karthik777/lego)'s, because that is a deploy that
works and it is made of the four packages this already talks to. `setup.py` there declares
the environment schema, writes `.env`, and generates the deploy workflow; `deploy.py` builds
the compose stack with dockeasy, opens the Cloudflare tunnel with cfeasy, and hands the
whole directory to vpseasy's `hetzner_deploy`, which provisions the VPS if it is missing and
rsyncs into it if it is not.

Leela does not reimplement any of that and does not try to drive those libraries from inside
the editor. It runs the project's own `deploy.py`, one subcommand per step, on the same pty
as a release -- so the output is the real thing, `nuke` is not reachable by accident, and a
project whose deploy already works keeps working exactly as it did from the command line.

What Leela adds is the two things the command line does not: the state (which stage ran,
what it exited with, what it printed) and the *first* `deploy.py`. `scaffold` writes the
lego pattern out for a project that has none -- dockeasy for the image, vpseasy for the
stack and the server, cfeasy for the tunnel and DNS, gheasy for the schema and the workflow
-- with this project's own name and domain in it. It is a starting point to edit, and it is
generated from the same libraries it imports, so there is one way these deploys work rather
than two.
"""

from __future__ import annotations

from pathlib import Path

from .envs import EnvStore
from .pipelines import Pipeline, PipelineError, Step

__all__ = ['Deploy', 'DeployError', 'DEPLOY_FILE', 'DEPLOY_KEYS', 'deploy_template']

DEPLOY_FILE = '.leela/deploy.json'
DeployError = PipelineError

# The schema a VPS deploy needs, in gheasy's shape: `None` is a secret, a string is a
# variable with that default. Every one of these is a key lego pushes, and the names are
# lego's so a project that already deploys keeps its values.
DEPLOY_KEYS = {
    'MODE': 'prod', 'PORT': '5001', 'DOMAIN': None, 'SERVER_NAME': None, 'SERVER_USER': 'deploy',
    'HCLOUD_TOKEN': None, 'CLOUDFLARE_API_TOKEN': None, 'CF_TUNNEL_TOKEN': None,
    'RSYNC_FORCE': 'false',
}

DEPLOY_STEPS = [
    Step('env', 'write .env', 'python deploy.py env',
         'Materialise the schema into .env, which the container reads and the deploy uploads.'),
    Step('compose', 'build the stack', 'python deploy.py compose',
         'dockeasy writes the Dockerfile; vpseasy writes docker-compose.yml and the Caddyfile.'),
    Step('deploy', 'tunnel and server', 'python deploy.py deploy',
         'cfeasy opens the Cloudflare tunnel, vpseasy provisions the VPS if needed and rsyncs.',
         ['HCLOUD_TOKEN', 'CLOUDFLARE_API_TOKEN']),
]


def deploy_template(app, domain, subdomain='', port=5001):
    """lego's `deploy.py`, with this project's names in it.

    Generated rather than copied so the parts that must agree do agree: the compose file
    mounts the Caddyfile this writes, the tunnel is named after the host it serves, and the
    rsync include list matches the files the stack actually needs. Everything it does is a
    call into dockeasy, vpseasy or cfeasy -- there is no deployment logic here, only the
    order the four of them go in.
    """
    host = f'{subdomain}.{domain}' if subdomain else domain
    tunnel = f'{subdomain or app}_{domain}'
    return f'''"""Deploy {app} to a VPS: dockeasy image, vpseasy stack and server, cfeasy tunnel.

Generated by Leela from the lego pattern. Edit freely -- it is your deploy, and the panel
runs whatever this file says.

    python deploy.py env       # write .env from the environment store
    python deploy.py compose   # Dockerfile + docker-compose.yml + Caddyfile
    python deploy.py deploy    # tunnel, server, rsync, up
    python deploy.py nuke      # delete the server and the tunnel
"""
import os, sys, secrets
from fastcore.all import Path
from dockeasy import detect_app, env_set, env_get
from cfeasy import CF
from vpseasy import caddy_stack, hetzner_deploy, Hetzner

root = Path(__file__).resolve().parent
app, domain, subdomain = {app!r}, {domain!r}, {subdomain!r}
host = {host!r}
tunnel_name = {tunnel!r}
srv, port = '/srv/app', {int(port)}
pkgs = ['curl']
vols = ['/app/data']
inc = ['{app}/', 'pyproject.toml', 'docker-compose.yml', 'main.py', 'Dockerfile', 'Caddyfile', '.env', 'uv.lock']
exc = ['data/', '.git/', '.venv/']

def mk_compose():
    "dockeasy detects what this project builds; vpseasy wraps it in Caddy and cloudflared."
    df = detect_app(str(root), pkgs=pkgs, vols=vols)
    return caddy_stack(host, df, vols=vols, root=root)

def mk_env():
    for k, v in (('MODE', 'prod'), ('PORT', str(port)), ('DOMAIN', host)):
        env_set(k, env_get(k, default=v), path=root/'.env')
    print(f'env: wrote {{root/".env"}}')

def deploy():
    "Idempotent: the tunnel is reused if it exists, the server provisioned only if it does not."
    mk_env()
    mk_compose()
    cf = CF()
    tid, tok = cf.setup_tunnel(domain, subdomain or None, tunnel_name=tunnel_name)
    print('cloudflare tunnel:', tid)
    env_set('CF_TUNNEL_TOKEN', tok, path=root/'.env')
    name = env_get('SERVER_NAME', path=root/'.env', default=app)
    user = env_get('SERVER_USER', path=root/'.env', default='deploy')
    r = hetzner_deploy(name, root, include=inc, exclude=exc, path=srv,
                       extra=os.getenv('RSYNC_FORCE') or None, user=user)
    env_set('HETZNER_IP', r.ip, path=root/'.env')
    print(f'deployed: https://{{host}} at {{r.ip}}')

def nuke():
    "Delete the server and the tunnel. Irreversible, so it asks for a token you have to read."
    typ = secrets.token_urlsafe(8)
    if input(f'This deletes the server and the tunnel. Type {{typ}} to proceed: ') != typ:
        return print('aborted')
    name = env_get('SERVER_NAME', path=root/'.env', default=app)
    Hetzner().delete(name)
    print(f'server {{name}} deleted')
    try:
        cf = CF()
        cf.delete_tunnel(cf.tunnel_id(tunnel_name))
        print('tunnel deleted')
    except Exception as e: print(f'tunnel not deleted: {{e}}')

if __name__ == '__main__':
    cmd = (sys.argv[1:] or [''])[0]
    if cmd == 'compose': mk_compose()
    elif cmd == 'env': mk_env()
    elif cmd == 'deploy': deploy()
    elif cmd == 'nuke': nuke()
    else: print('usage: deploy.py env | compose | deploy | nuke')
'''


class Deploy(Pipeline):
    "The deploy pipeline: the project's own `deploy.py`, one subcommand per step."

    FILE = DEPLOY_FILE
    KIND = 'deploy'

    @staticmethod
    def defaults(root): return list(DEPLOY_STEPS)

    def target(self):
        """Where this deploy goes and what it is still missing.

        Values come from the same store the steps will read, so "DOMAIN is set" here and
        `DOMAIN` reaching the container are the same fact rather than two that can disagree.
        """
        store = self.env if isinstance(self.env, EnvStore) else EnvStore()
        def value(key, default=''):
            try: return store.get(key, secret=False) or default
            except Exception: return default
        missing = []
        for key, default in DEPLOY_KEYS.items():
            if default is None:
                try: found = store.get(key)
                except Exception: found = ''
                if not found: missing.append(key)
        return {'app': value('APP') or self.root.name, 'domain': value('DOMAIN'),
                'server': value('SERVER_NAME'), 'user': value('SERVER_USER', 'deploy'),
                'port': value('PORT', '5001'), 'missing': missing,
                'script': (self.root/'deploy.py').exists(),
                'compose': (self.root/'docker-compose.yml').exists(),
                'dockerfile': (self.root/'Dockerfile').exists(),
                'caddyfile': (self.root/'Caddyfile').exists(),
                'keys': {k: (v is None) for k, v in DEPLOY_KEYS.items()}}

    def state(self):
        return super().state() | {'target': self.target()}

    def scaffold(self, domain='', subdomain='', app='', force=False):
        """Write the first `deploy.py`, and the schema and workflow that go with it.

        Three files, each from the library that owns it: the script imports dockeasy,
        vpseasy and cfeasy; the schema is a gheasy `GheasyConfig`; the workflow is gheasy's
        DSL through `leela.workflows`. Refuses to overwrite an existing `deploy.py` unless
        told to -- a deploy script is usually the most edited file in a repository.
        """
        domain = str(domain or '').strip()
        if not domain: raise DeployError('a domain is required — the host this app answers on')
        app = str(app or '').strip() or self.root.name
        script = self.root/'deploy.py'
        if script.exists() and not force:
            raise DeployError('this project already has a deploy.py')
        written = []
        script.write_text(deploy_template(app, domain, str(subdomain or '').strip(),
                                          int(self.target()['port'] or 5001)), encoding='utf-8')
        written.append(str(script))
        try:
            from gheasy.core import GheasyConfig, cfg_path
            cfg = GheasyConfig.load(str(self.root))
            cfg.app = cfg.app or app
            cfg.env_schema = {**DEPLOY_KEYS, **(cfg.env_schema or {})}
            cfg.save(str(self.root))
            written.append(str(cfg_path(str(self.root))))
        except ImportError:
            pass                                  # gheasy is optional; the script still stands
        try:
            from .workflows import Workflows
            written.append(Workflows(self.root).add('deploy')['path'])
        except Exception:
            pass                                  # a workflow that already exists is not a failure
        return {'written': written, 'state': self.state()}
